import ts from 'typescript';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../lib/catalog.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {demoProducts,available,orderMessage}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const p=demoProducts[0];
assert.equal(available({...p,status:'Sold Out'}),false);
assert.equal(available({...p,stock:0}),false);
assert.equal(available({...p,stock:2}),true);
const items=[{product:{...p,name:'Tas & Travel / Mini',demo:false},color:'Cream & Gold',size:'M',quantity:2},{product:demoProducts[1],color:'Hitam',size:'',quantity:1}];
const message=orderMessage(items,'https://example.com');
assert.match(message,/1\. Tas & Travel \/ Mini/);
assert.match(message,/Cream & Gold \/ M/);
assert.match(message,/Jumlah: 2/);
assert.match(message,/2\. Classic Shoulder Bag/);
assert.match(message,/https:\/\/example.com\/products\/the-everyday-tote/);
assert.match(message,/katalog demo/);
assert.equal(decodeURIComponent(encodeURIComponent(message)),message);
assert.equal(new Set(demoProducts.map(p=>p.slug)).size,demoProducts.length);
console.log('Catalog checks passed: availability, multiple-item WhatsApp messages, variants, links, encoding, demo disclosure, unique slugs.');
